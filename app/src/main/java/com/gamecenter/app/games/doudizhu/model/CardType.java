package com.gamecenter.app.games.doudizhu.model;

/**
 * 斗地主牌型枚举，定义了游戏中所有合法的出牌组合类型。
 * <p>
 * 职责：
 * <ul>
 *   <li>枚举所有合法牌型，作为牌型判定的返回值</li>
 *   <li>提供牌型之间的比较规则（canBeat 方法），判断一种牌型是否能打过另一种</li>
 *   <li>区分炸弹/王炸与普通牌型，炸弹可以压制任意非炸弹牌型</li>
 * </ul>
 * <p>
 * 关键设计决策：
 * <ul>
 *   <li>每个枚举值携带中文名称(name)和优先级(priority)，优先级用于牌型间的宏观比较</li>
 *   <li>ERROR 类型用于标记非法牌型，避免使用 null 返回值带来的空指针风险</li>
 *   <li>四带两单(QUAD_SINGLE)和四带两对(QUAD_PAIR)不是炸弹，priority 与三带牌型相同，
 *       这符合标准斗地主规则：四带二不算炸弹，不能压制其他牌型</li>
 *   <li>炸弹(BOMB)和王炸(JOKER_BOMB)拥有最高优先级，可以打任意牌型</li>
 * </ul>
 */
public enum CardType {
    /**
     * 无效牌型 —— 当输入的牌无法组成任何合法牌型时返回此类型。
     * 例如：两张不同牌值的牌、不连续的散牌等。
     */
    ERROR("错误牌型", 0),

    /**
     * 单牌 —— 任意一张单独的牌。
     * 最基本的出牌单位，任何单张牌都可以作为单牌出。
     */
    SINGLE("单牌", 1),

    /**
     * 对子 —— 两张牌值相同的牌。
     * 例如：两个3、两个K。注意：两张王不算对子，算王炸。
     */
    PAIR("对子", 2),

    /**
     * 三张 —— 三张牌值相同的牌。
     * 在标准斗地主中，三张不能单独出，必须带一张单牌或一对。
     * 但此处保留纯三张类型，用于飞机牌型的组成部分判定。
     */
    TRIO("三张", 3),

    /**
     * 三带一 —— 三张相同牌值 + 任意一张单牌。
     * 例如：333+5、KKK+7。附带的那张单牌不参与大小比较。
     */
    TRIO_SINGLE("三带一", 4),

    /**
     * 三带一对 —— 三张相同牌值 + 一对。
     * 例如：333+55、KKK+77。附带的对子不参与大小比较。
     */
    TRIO_PAIR("三带一对", 5),

    /**
     * 顺子（单顺）—— 五张或更多连续单牌。
     * 规则限制：
     * <ul>
     *   <li>最少5张，无上限</li>
     *   <li>牌值必须连续（如34567、10JQKA）</li>
     *   <li>不能包含2和王</li>
     *   <li>A既可作最高牌（...JQKA），也可作最低牌（A2345不合法）</li>
     * </ul>
     */
    STRAIGHT("顺子", 6),

    /**
     * 连对（双顺）—— 三对或更多连续对子。
     * 规则限制：
     * <ul>
     *   <li>最少3对（6张牌）</li>
     *   <li>对子的牌值必须连续（如33-44-55）</li>
     *   <li>不能包含2和王</li>
     * </ul>
     */
    STRAIGHT_PAIRS("连对", 7),

    /**
     * 飞机 —— 两个或更多连续三张，不带任何附带牌。
     * 例如：333-444、555-666-777。
     * 三张的牌值必须连续，且不能包含2。
     */
    AIRPLANE("飞机", 8),

    /**
     * 飞机带翅膀 —— 飞机 + 相应数量的单牌或对子。
     * 翅膀数量必须与飞机的三张组数一致：
     * <ul>
     *   <li>带单牌：333-444+5+6（2组三张带2张单牌）</li>
     *   <li>带对子：333-444+55+66（2组三张带2对）</li>
     * </ul>
     */
    AIRPLANE_WITH_WINGS("飞机带翅膀", 9),

    /**
     * 炸弹 —— 四张牌值相同的牌。
     * 炸弹是特殊牌型，可以压制任何非炸弹/王炸的牌型。
     * 炸弹之间按牌值大小比较，大的炸弹压制小的炸弹。
     * 每出一个炸弹，游戏倍数翻倍。
     */
    BOMB("炸弹", 10),

    /**
     * 王炸（火箭）—— 小王 + 大王。
     * 斗地主中最大的牌型，可以压制包括炸弹在内的所有牌型。
     * 每出一次王炸，游戏倍数翻两倍。
     */
    JOKER_BOMB("王炸", 11),

    /**
     * 四带两单 —— 四张相同牌值 + 两张单牌。
     * 注意：四带二不是炸弹！不能压制其他牌型，只能与同牌型比较。
     * 例如：3333+5+7、KKKK+3+4。
     */
    QUAD_SINGLE("四带两单", 4),

    /**
     * 四带两对 —— 四张相同牌值 + 两对。
     * 注意：四带两对不是炸弹！不能压制其他牌型，只能与同牌型比较。
     * 例如：3333+55+66、KKKK+99+10-10。
     */
    QUAD_PAIR("四带两对", 5);

    private final String name;
    private final int priority;

    /**
     * 枚举构造函数。
     *
     * @param name     牌型的中文名称，用于 UI 显示和日志输出
     * @param priority 牌型的优先级，数值越大优先级越高；炸弹和王炸拥有最高优先级
     */
    CardType(String name, int priority) {
        this.name = name;
        this.priority = priority;
    }

    /**
     * 获取牌型的中文名称。
     *
     * @return 牌型名称，如 "单牌"、"炸弹"、"王炸" 等
     */
    public String getName() {
        return name;
    }

    /**
     * 获取牌型的优先级。
     * <p>
     * 优先级用于宏观比较不同牌型之间的压制关系：
     * 炸弹(10)和王炸(11)可以压制所有低优先级牌型。
     * 四带二(4)与三带一(4)优先级相同，说明四带二不是炸弹。
     *
     * @return 优先级数值，0~11
     */
    public int getPriority() {
        return priority;
    }

    /**
     * 判断当前牌型是否为错误牌型。
     * <p>
     * 在牌型判定流程中，如果返回 ERROR，说明玩家选择的牌不构成合法牌型，
     * 应提示玩家重新选择。
     *
     * @return 如果是 ERROR 类型返回 true，否则返回 false
     */
    public boolean isError() {
        return this == ERROR;
    }

    /**
     * 判断当前牌型是否为炸弹或王炸。
     * <p>
     * 炸弹和王炸是斗地主中的特殊牌型，可以压制任何其他牌型。
     * 注意：四带二（QUAD_SINGLE/QUAD_PAIR）不是炸弹。
     *
     * @return 如果是 BOMB 或 JOKER_BOMB 返回 true，否则返回 false
     */
    public boolean isBomb() {
        return this == BOMB || this == JOKER_BOMB;
    }

    /**
     * 判断当前牌型是否可以打过（压制）指定的牌型。
     * <p>
     * 压制规则：
     * <ol>
     *   <li>王炸可以打任意牌型（包括炸弹）</li>
     *   <li>炸弹可以打任意非炸弹牌型</li>
     *   <li>同牌型之间需要比较主权重才能确定是否打得过（此方法仅判断牌型兼容性）</li>
     *   <li>不同牌型（非炸弹/王炸）之间不能互相压制</li>
     * </ol>
     * <p>
     * 注意：此方法仅判断牌型层面的兼容性，实际能否打过还需要比较主权重。
     * 例如两个顺子，牌型相同（canBeat 返回 true），但还需比较主权重大小。
     *
     * @param other 对方打出的牌型，null 表示对方未出牌（自由出牌）
     * @return 如果牌型上可以压制对方返回 true，否则返回 false
     */
    public boolean canBeat(CardType other) {
        if (other == null) {
            return true;
        }
        if (this == JOKER_BOMB) {
            return true;
        }
        if (this == BOMB && !other.isBomb()) {
            return true;
        }
        return this == other;
    }
}
