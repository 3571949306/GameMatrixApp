package com.gamecenter.app.games.common;

/**
 * 游戏逻辑通用接口，定义所有游戏应遵循的核心契约。
 *
 * <p>设计目标：
 * <ul>
 *   <li>将游戏状态和规则与 UI 层解耦，使逻辑层可独立测试和复用</li>
 *   <li>通过泛型参数 {@code S} 允许不同游戏定义各自的状态类型</li>
 *   <li>提供统一的状态查询、动作执行和游戏生命周期管理方法</li>
 * </ul>
 *
 * <p>关键设计决策：
 * <ul>
 *   <li>使用 {@link Object} 作为 action 参数类型，以兼容不同游戏的操作类型，
 *       具体实现应自行进行类型转换和校验</li>
 *   <li>不包含 UI 相关方法，保持纯逻辑职责</li>
 * </ul>
 *
 * @param <S> 游戏状态类型，由具体游戏定义（如棋盘数组、牌组列表等）
 */
public interface GameLogic<S> {

    /**
     * 获取当前游戏状态的快照。
     *
     * <p>返回的状态对象应能完整描述当前游戏局面，供 UI 层渲染或 AI 层分析使用。
     *
     * @return 当前游戏状态
     */
    S getState();

    /**
     * 对当前游戏状态执行一个动作（操作）。
     *
     * <p>具体实现应负责：
     * <ul>
     *   <li>验证动作的合法性（非法动作可抛出异常或静默忽略）</li>
     *   <li>更新内部游戏状态</li>
     *   <li>触发副作用（如切换玩家、记录历史等）</li>
     * </ul>
     *
     * @param action 要执行的动作，具体类型由实现定义
     */
    void applyAction(Object action);

    /**
     * 判断游戏是否已结束。
     *
     * <p>结束条件由具体游戏定义（如一方获胜、平局、无合法走法等）。
     *
     * @return 如果游戏已结束返回 true
     */
    boolean isGameOver();

    /**
     * 获取获胜方编号。
     *
     * <p>仅在 {@link #isGameOver()} 返回 true 时调用才有意义。
     * 平局等无获胜方的情况可返回约定的特殊值（如 -1）。
     *
     * @return 获胜方编号，具体含义由实现定义
     */
    int getWinner();

    /**
     * 重置游戏到初始状态。
     *
     * <p>调用后游戏应回到开始时的初始局面，等同于重新开始一局。
     */
    void reset();
}
